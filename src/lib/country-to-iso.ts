export function countryNameToIso2(country: string): string | null {
  const k = country.trim();
  if (!k) return null;
  if (COUNTRY_TO_ISO[k]) return COUNTRY_TO_ISO[k];
  const lower = k.toLowerCase();
  for (const [name, code] of Object.entries(COUNTRY_TO_ISO)) {
    if (name.toLowerCase() === lower) return code;
  }
  return null;
}
